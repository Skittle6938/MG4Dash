"""Generates the 19 extra backgrounds and accents (dark and light) of the extended palette, in themes_palette.xml,
and prints the Kotlin lists. Derivations follow the existing hand-made styles."""
import colorsys
import os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'main')

def hx(rgb, a=0xFF): return '#%02X%02X%02X%02X' % (a, *[max(0, min(255, round(c))) for c in rgb])
def hls(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h / 360, l, s); return (r * 255, g * 255, b * 255)
def mul(c, k): return tuple(x * k for x in c)
def mix(c, d, t): return tuple(x + (y - x) * t for x, y in zip(c, d))
def parse(h): h = h.lstrip('#'); return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))

# (name, hue, saturation) of the extra backgrounds; lightness is set by the derivation
# The four first ones replace the hand-made Night, Charcoal, Forest and Burgundy (24/11: too alike); Black stays hand-made
BASE = [('Night', 225, .30), ('Charcoal', 216, .08), ('Forest', 160, .26), ('Burgundy', 345, .32)]
BGS = BASE + [('Slate', 205, .18), ('Petrol', 195, .40), ('Teal', 175, .35), ('Emerald', 140, .38), ('Moss', 100, .20), ('Olive', 70, .25),
       ('Sand', 40, .15), ('Bronze', 35, .35), ('Brown', 25, .30), ('Rust', 15, .40), ('DeepRed', 0, .40), ('Wine', 322, .30),
       ('Plum', 300, .25), ('Purple', 275, .30), ('Indigo', 245, .35), ('Midnight', 230, .45), ('Steel', 200, .22), ('Graphite', 0, 0.0),
       ('WarmGrey', 30, .08)]
ACS = [('Cyan', '00B8D4'), ('Teal', '00BFA5'), ('Turquoise', '1DE9B6'), ('LightGreen', '64DD17'), ('Lime', 'AEEA00'), ('Yellow', 'FFD600'),
       ('Gold', 'FFC400'), ('Amber', 'FFAB00'), ('DeepOrange', 'FF6D00'), ('Coral', 'FF6E40'), ('Rose', 'FF4081'), ('Pink', 'F50057'),
       ('Magenta', 'D500F9'), ('Purple', 'AA00FF'), ('DeepPurple', '7C4DFF'), ('Lavender', 'B388FF'), ('Indigo', '536DFE'), ('LightBlue', '00B0FF'),
       ('Sky', '40C4FF')]

TEXT_D = ['<item name="mgTextValue">#FFFFFFFF</item>', '<item name="mgTextTitle">#FF8A94A6</item>', '<item name="mgTextSub">#FFA0AEC0</item>', '<item name="mgTextDisabled">#FF4A5366</item>']
TEXT_L = ['<item name="mgTextValue">#FF141922</item>', '<item name="mgTextTitle">#FF5A6475</item>', '<item name="mgTextSub">#FF4A5466</item>', '<item name="mgTextDisabled">#FFA3ABB8</item>']
xml = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Extended palette (24/11): generated by a script from the hand-made styles in themes_colors.xml; do not edit by hand. -->', '<resources>']
swatches_bg, swatches_ac = [], []
def style(name, items): xml.append(f'    <style name="{name}" parent="">'); xml.extend('        ' + i for i in items); xml.append('    </style>')

for n, h, s in BGS:
    # Clearly tinted (24/11: the first try looked all alike): more saturation, a little more light
    sd = min(.85, s * 1.6 + .12) if s > 0 else 0.0
    L = lambda l: hls(h, l, sd)
    idle = L(.14); swatches_bg.append(hx(idle))
    style(f'MgBg.{n}', [f'<item name="mgBgTop">{hx(L(.065))}</item>', f'<item name="mgBgBottom">{hx(L(.12))}</item>', f'<item name="mgBgEnd">{hx(L(.085))}</item>',
        f'<item name="mgPanel">{hx(L(.10), 0xD9)}</item>', f'<item name="mgPanelBorder">{hx(L(.20))}</item>', f'<item name="mgButtonIdle">{hx(idle)}</item>',
        f'<item name="mgButtonPressed">{hx(L(.19))}</item>', f'<item name="mgGaugeOff">{hx(L(.165))}</item>', f'<item name="mgPill">{hx(L(.10), 0xCC)}</item>',
        f'<item name="mgButtonDisabled">{hx(idle, 0x80)}</item>'] + TEXT_D)
    sl = min(.60, s * 1.5 + .15) if s > 0 else 0.0
    LL = lambda l: hls(h, l, sl)
    style(f'MgBgLight.{n}', [f'<item name="mgBgTop">{hx(LL(.885))}</item>', f'<item name="mgBgBottom">{hx(LL(.94))}</item>', f'<item name="mgBgEnd">{hx(LL(.91))}</item>',
        f'<item name="mgPanel">{hx(LL(.975), 0xE6)}</item>', f'<item name="mgPanelBorder">{hx(LL(.76))}</item>', f'<item name="mgButtonIdle">{hx(LL(.865))}</item>',
        f'<item name="mgButtonPressed">{hx(LL(.81))}</item>', f'<item name="mgGaugeOff">{hx(LL(.83))}</item>', f'<item name="mgPill">{hx(LL(.975), 0xCC)}</item>',
        f'<item name="mgButtonDisabled">{hx(LL(.865), 0x80)}</item>'] + TEXT_L)

W, K = (255, 255, 255), (0, 0, 0)
for n, a in ACS:
    A = parse(a); swatches_ac.append('#FF' + a)
    sel = mix(A, W, .45)
    style(f'MgAccent.{n}', [f'<item name="mgAction">{hx(A)}</item>', f'<item name="mgSelect">{hx(sel)}</item>', f'<item name="mgActionPressed">{hx(mul(A, .7))}</item>',
        f'<item name="mgActionDeep">{hx(mul(A, .45))}</item>', f'<item name="mgActionDeeper">{hx(mul(A, .32))}</item>', f'<item name="mgActionBorder">{hx(mix(A, W, .18))}</item>',
        f'<item name="mgActionTint">{hx(A, 0x26)}</item>', f'<item name="mgSelectTint">{hx(sel, 0x26)}</item>', f'<item name="colorAccent">{hx(A)}</item>'])
    # Light: darker, so a value in the accent stays readable on white (as the hand-made light accents)
    lum = (0.2126 * A[0] + 0.7152 * A[1] + 0.0722 * A[2]) / 255
    k = min(.84, .42 / max(lum, .01))
    AL = mul(A, k); SL = mul(A, min(.7, .32 / max(lum, .01)))
    style(f'MgAccentLight.{n}', [f'<item name="mgAction">{hx(AL)}</item>', f'<item name="mgSelect">{hx(SL)}</item>', f'<item name="mgActionPressed">{hx(mul(AL, .7))}</item>',
        f'<item name="mgActionDeep">{hx(mul(AL, .45))}</item>', f'<item name="mgActionDeeper">{hx(mul(AL, .32))}</item>', f'<item name="mgActionBorder">{hx(mix(AL, W, .18))}</item>',
        f'<item name="mgActionTint">{hx(AL, 0x26)}</item>', f'<item name="mgSelectTint">{hx(SL, 0x26)}</item>', f'<item name="colorAccent">{hx(AL)}</item>'])
xml.append('</resources>')
open(os.path.join(R, 'res', 'values', 'themes_palette.xml'), 'w', encoding='utf-8', newline='\n').write('\n'.join(xml) + '\n')

print('themes_palette.xml written; the Kotlin lists in ui/Themes.kt follow the same order')
print('BACKGROUND_SWATCHES (0, 2, 3, 4, then 5-23):', ', '.join(swatches_bg))
