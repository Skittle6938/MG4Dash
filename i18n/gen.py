import re, os, sys
from collections import Counter
from pathlib import Path
# Generates app/src/main/res/values*/strings.xml from i18n/strings.psv
rows = [l.rstrip('\n').split('|') for l in open('i18n/strings.psv', encoding='utf-8') if l.strip()]
hdr = rows[0][1:]
rows = rows[1:]
keys = [row[0] for row in rows]
if len(keys) != len(set(keys)):
    raise SystemExit('Duplicate translation keys')
placeholder = re.compile(r'%(?:(\d+)\$)?[-#+0,(]*\d*(?:\.\d+)?([a-zA-Z])')

def arguments(value):
    matches = placeholder.findall(value.replace('%%', ''))
    return Counter((index or str(i + 1), kind) for i, (index, kind) in enumerate(matches))
for row in rows:
    if len(row) != len(hdr) + 1 or any(not value.strip() for value in row):
        raise SystemExit(f'{row[0]}: missing translation or invalid column count')
    expected = arguments(row[1])
    for lang, value in zip(hdr, row[1:]):
        if arguments(value) != expected:
            raise SystemExit(f'{row[0]} ({lang}): format arguments differ from English')
BS = chr(92)

def esc(s):
    if not re.search(r'%\d\$', s):
        s = s.replace('%%', '%')
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace(BS, BS + BS).replace("'", BS + "'").replace('"', BS + '"')
    s = s.replace(BS + BS + 'n', BS + 'n')   # BS+n in the psv: line break
    if s != s.strip():
        s = '"' + s + '"'
    return s

# rescueapp_* keys: MG4Dash Rescue's own texts (rescue/src/main/res), the others MG4Dash's
for module, wanted in (('app', lambda k: not k.startswith('rescueapp_')), ('rescue', lambda k: k.startswith('rescueapp_'))):
  for i, lang in enumerate(hdr):
    d = module + '/src/main/res/values' + ('' if lang == 'en' else '-' + lang)
    os.makedirs(d, exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by i18n/gen.py from i18n/strings.psv -->', '<resources>']
    items = [(r[0], r[1 + i]) for r in rows if wanted(r[0])]
    for k, v in items:
        fmt = ' formatted="false"' if ('%' in v and not placeholder.search(v)) else ''
        out.append(f'    <string name="{k}"{fmt}>{esc(v)}</string>')
    out.append('</resources>\n')
    generated = '\n'.join(out)
    path = Path(d) / 'strings.xml'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8-sig') != generated:
            raise SystemExit(f'{path}: run python i18n/gen.py and commit the generated files')
    else:
        path.write_text(generated, encoding='utf-8', newline='\n')
    print(d, len(items))
