#!/usr/bin/env python3
"""Generates the overlay's layouts and a stub SystemUI to compile them against (#113).

SystemUI versions number the fog light icons differently (img_front_lamp 0x7f0800b8 on SWI69's .222, 0x7f0800b6 on
SWI173's .153), and a layout overlay keeps the numbers it was compiled with: one compiled for a single SystemUI left
another without a front lamp, a crash at each of SystemUI's starts. So layout_ball (and layout_ball_as33) get one
0 x 0 ImageView per id of a whole range: whatever numbers a SystemUI gives its two lamps inside that range,
FloatBallView finds both, at size 0. MG4Dash only enables the overlay when both ids fall in the range
(FogOverlay.ID_FIRST / ID_LAST, keep them equal to FIRST / LAST here).

The stub (package com.android.systemui, ids pinned with --stable-ids) only serves to resolve the references.
"""
import os
FIRST, LAST = 0x7f080040, 0x7f08017f
here = os.path.dirname(os.path.abspath(__file__))
ids = range(FIRST, LAST + 1)
name = lambda i: "i_%08x" % i

stub = os.path.join(here, "build", "stub")
os.makedirs(os.path.join(stub, "res", "values"), exist_ok=True)
with open(os.path.join(stub, "AndroidManifest.xml"), "w") as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="com.android.systemui" />\n')
with open(os.path.join(stub, "res", "values", "ids.xml"), "w") as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n')
    f.writelines('    <item type="id" name="%s" />\n' % name(i) for i in ids)
    f.write('</resources>\n')
with open(os.path.join(here, "build", "stable-ids.txt"), "w") as f:
    f.writelines("com.android.systemui:id/%s = 0x%08x\n" % (name(i), i) for i in ids)

layout = ['<?xml version="1.0" encoding="utf-8"?>',
          '<!-- Generated by gen.py: one 0 x 0 ImageView per id 0x%08x..0x%08x, so FloatBallView finds both lamps whatever' % (FIRST, LAST),
          '     their numbers in that range; the window has no size and takes no touch (#113) -->',
          '<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"',
          '    android:orientation="horizontal"',
          '    android:background="@android:color/transparent"',
          '    android:layout_width="wrap_content"',
          '    android:layout_height="wrap_content">']
layout += ['    <ImageView android:id="@*com.android.systemui:id/%s" android:layout_width="0dp" android:layout_height="0dp" />' % name(i) for i in ids]
layout += ['</LinearLayout>', '']
os.makedirs(os.path.join(here, "res", "layout"), exist_ok=True)
for n in ("layout_ball.xml", "layout_ball_as33.xml"):
    with open(os.path.join(here, "res", "layout", n), "w") as f:
        f.write("\n".join(layout))
print("%d ids, 0x%08x..0x%08x" % (len(ids), FIRST, LAST))
